  KEY `idx_purchase_bill_inbox_party` (`tenant_id`,`supplier_name`),
  CONSTRAINT `fk_purchase_bill_inbox_tenant_id` FOREIGN KEY (`tenant_id`) REFERENCES `sys_tenant` (`tenant_id`) ON DELETE CASCADE ON UPDATE CASCADE,
